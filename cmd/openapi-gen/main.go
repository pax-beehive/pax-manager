package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type thriftDoc struct {
	Structs map[string]thriftStruct
	Methods []thriftMethod
}

type thriftStruct struct {
	Name   string
	Fields []thriftField
}

type thriftField struct {
	Name     string
	Type     string
	Required bool
}

type thriftMethod struct {
	Name        string
	ReturnType  string
	RequestType string
	Annotations map[string]string
}

func main() {
	in := flag.String("in", "", "input Thrift file")
	out := flag.String("out", "", "output Go file")
	flag.Parse()
	if *in == "" || *out == "" {
		fatalf("-in and -out are required")
	}
	data, err := os.ReadFile(*in)
	if err != nil {
		fatalf("read thrift: %v", err)
	}
	doc, err := parseThrift(string(data))
	if err != nil {
		fatalf("parse thrift: %v", err)
	}
	spec := buildSpec(doc)
	specJSON, err := json.MarshalIndent(spec, "", "  ")
	if err != nil {
		fatalf("marshal openapi: %v", err)
	}
	src := bytes.Buffer{}
	src.WriteString("package manager\n\n")
	src.WriteString("import (\n")
	src.WriteString("\"encoding/json\"\n\n")
	src.WriteString("hertzserver \"github.com/cloudwego/hertz/pkg/app/server\"\n")
	src.WriteString(")\n\n")
	src.WriteString(
		"// Code generated by cmd/openapi-gen from api/pax_manager.thrift; DO NOT EDIT.\n",
	)
	src.WriteString("func openAPIBaseDocument() map[string]any {\n")
	src.WriteString("var doc map[string]any\n")
	src.WriteString("if err := json.Unmarshal([]byte(openAPIBaseJSON), &doc); err != nil {\n")
	src.WriteString("panic(err)\n")
	src.WriteString("}\n")
	src.WriteString("return doc\n")
	src.WriteString("}\n\n")
	src.WriteString("func registerIDLRoutes(h *hertzserver.Hertz) {\n")
	for _, method := range doc.Methods {
		httpMethod, path := httpRoute(method.Annotations)
		if httpMethod == "" || path == "" {
			continue
		}
		handler := method.Name
		src.WriteString("h.")
		src.WriteString(httpMethod)
		src.WriteString("(")
		src.WriteString(strconv.Quote(path))
		src.WriteString(", ")
		if method.Annotations["openapi.security"] == "agentBearer" {
			src.WriteString("AgentAuth(), ")
		}
		src.WriteString(handler)
		src.WriteString(")\n")
	}
	src.WriteString("}\n\n")
	src.WriteString("const openAPIBaseJSON = `")
	src.Write(specJSON)
	src.WriteString("`\n")
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		fatalf("format generated go: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fatalf("write generated go: %v", err)
	}
}

func parseThrift(src string) (thriftDoc, error) {
	doc := thriftDoc{Structs: map[string]thriftStruct{}}
	lines := strings.Split(src, "\n")
	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(stripComment(lines[i]))
		if strings.HasPrefix(line, "struct ") {
			st, next, err := parseStruct(lines, i)
			if err != nil {
				return doc, err
			}
			doc.Structs[st.Name] = st
			i = next
			continue
		}
		if strings.HasPrefix(line, "service ") {
			methods, next, err := parseService(lines, i)
			if err != nil {
				return doc, err
			}
			doc.Methods = append(doc.Methods, methods...)
			i = next
		}
	}
	return doc, nil
}

func parseStruct(lines []string, start int) (thriftStruct, int, error) {
	header := strings.TrimSpace(stripComment(lines[start]))
	name := strings.Fields(header)[1]
	name = strings.TrimSuffix(name, "{")
	st := thriftStruct{Name: name}
	fieldRE := regexp.MustCompile(
		`^\s*\d+:\s+(required|optional)\s+(.+?)\s+([A-Za-z_][A-Za-z0-9_]*)\b`,
	)
	for i := start + 1; i < len(lines); i++ {
		line := stripComment(lines[i])
		if strings.Contains(line, "}") {
			return st, i, nil
		}
		matches := fieldRE.FindStringSubmatch(line)
		if matches == nil {
			continue
		}
		st.Fields = append(st.Fields, thriftField{
			Name:     matches[3],
			Type:     strings.TrimSpace(matches[2]),
			Required: matches[1] == "required",
		})
	}
	return st, len(lines) - 1, fmt.Errorf("struct %s was not closed", name)
}

func parseService(lines []string, start int) ([]thriftMethod, int, error) {
	var methods []thriftMethod
	methodRE := regexp.MustCompile(
		`^\s*([A-Za-z_][A-Za-z0-9_]*)\s+([A-Za-z_][A-Za-z0-9_]*)\((.*)\)`,
	)
	for i := start + 1; i < len(lines); i++ {
		line := strings.TrimSpace(stripComment(lines[i]))
		if strings.Contains(line, "}") {
			return methods, i, nil
		}
		matches := methodRE.FindStringSubmatch(line)
		if matches == nil {
			continue
		}
		method := thriftMethod{
			ReturnType:  matches[1],
			Name:        matches[2],
			RequestType: requestType(matches[3]),
		}
		annotationText := ""
		if strings.Contains(line, "(") && strings.Contains(line, ")") &&
			strings.Contains(line, "http.") {
			annotationText = line[strings.Index(line, "("):]
		} else if i+1 < len(lines) {
			next := strings.TrimSpace(stripComment(lines[i+1]))
			if strings.HasPrefix(next, "(") {
				annotationText = next
				i++
			}
		}
		method.Annotations = parseAnnotations(annotationText)
		methods = append(methods, method)
	}
	return methods, len(lines) - 1, fmt.Errorf("service was not closed")
}

func requestType(args string) string {
	args = strings.TrimSpace(args)
	if args == "" {
		return ""
	}
	parts := strings.Fields(args)
	if len(parts) >= 2 {
		return parts[1]
	}
	return ""
}

func parseAnnotations(raw string) map[string]string {
	out := map[string]string{}
	raw = strings.TrimSpace(raw)
	raw = strings.TrimPrefix(raw, "(")
	raw = strings.TrimSuffix(raw, ")")
	re := regexp.MustCompile(`([A-Za-z0-9_.-]+)\s*=\s*"([^"]*)"`)
	for _, match := range re.FindAllStringSubmatch(raw, -1) {
		out[match[1]] = match[2]
	}
	return out
}

func buildSpec(doc thriftDoc) map[string]any {
	paths := map[string]any{}
	for _, method := range doc.Methods {
		httpMethod, path := httpRoute(method.Annotations)
		httpMethod = strings.ToLower(httpMethod)
		path = openAPIPath(path)
		if httpMethod == "" || path == "" {
			continue
		}
		pathItem, _ := paths[path].(map[string]any)
		if pathItem == nil {
			pathItem = map[string]any{}
			paths[path] = pathItem
		}
		pathItem[httpMethod] = operation(method)
	}
	return map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       "pax-manager Fleet Control Plane API",
			"version":     "0.1.0",
			"description": "Cloud API for paxd registration, mailbox delivery, session snapshots, and user-managed platform API keys.",
		},
		"tags": []map[string]string{
			{"name": "system", "description": "Health and metadata endpoints."},
			{
				"name":        "agent",
				"description": "paxd-facing endpoints authenticated with bearer agent API keys.",
			},
			{"name": "user", "description": "Cloudflare Access user endpoints."},
		},
		"paths": paths,
		"components": map[string]any{
			"securitySchemes": map[string]any{
				"agentBearer": map[string]any{
					"type":        "http",
					"scheme":      "bearer",
					"description": "Agent API key returned during registration.",
				},
				"cloudflareAccess": map[string]any{
					"type":        "apiKey",
					"in":          "header",
					"name":        "Cf-Access-Jwt-Assertion",
					"description": "Cloudflare Access JWT assertion header.",
				},
			},
			"schemas": schemas(doc.Structs),
		},
	}
}

func operation(method thriftMethod) map[string]any {
	status := method.Annotations["openapi.status"]
	if status == "" {
		status = "200"
	}
	responses := map[string]any{
		status: response("Successful response.", method.ReturnType),
		"400":  response("Invalid request.", "ErrorResponse"),
		"401":  response("Unauthorized.", "ErrorResponse"),
		"404":  response("Not found.", "ErrorResponse"),
		"500":  response("Internal server error.", "ErrorResponse"),
	}
	op := map[string]any{
		"tags":        []string{method.Annotations["openapi.tag"]},
		"summary":     method.Annotations["openapi.summary"],
		"description": method.Annotations["openapi.description"],
		"responses":   responses,
	}
	if method.RequestType != "" {
		op["requestBody"] = map[string]any{
			"required": true,
			"content": map[string]any{
				"application/json": map[string]any{"schema": schemaRef(method.RequestType)},
			},
		}
	}
	parameters := parameters(method.Annotations)
	if len(parameters) > 0 {
		op["parameters"] = parameters
	}
	if security := method.Annotations["openapi.security"]; security != "" {
		op["security"] = []map[string][]string{{security: {}}}
	}
	return op
}

func parameters(annotations map[string]string) []map[string]any {
	var keys []string
	for key := range annotations {
		if strings.HasPrefix(key, "openapi.path.") || strings.HasPrefix(key, "openapi.query.") ||
			strings.HasPrefix(key, "openapi.header.") {
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	var out []map[string]any
	for _, key := range keys {
		location, name := parameterLocation(key)
		required := location == "path" || location == "header"
		out = append(out, map[string]any{
			"name":        name,
			"in":          location,
			"required":    required,
			"description": annotations[key],
			"schema":      parameterSchema(name),
		})
	}
	return out
}

func parameterLocation(key string) (string, string) {
	for _, prefix := range []string{"openapi.path.", "openapi.query.", "openapi.header."} {
		if strings.HasPrefix(key, prefix) {
			location := strings.TrimPrefix(strings.TrimSuffix(prefix, "."), "openapi.")
			return location, parameterName(strings.TrimPrefix(key, prefix))
		}
	}
	return "query", key
}

func parameterName(name string) string {
	switch name {
	case "XRegistrationToken":
		return "X-Registration-Token"
	default:
		return name
	}
}

func parameterSchema(name string) map[string]string {
	switch name {
	case "limit", "offset":
		return map[string]string{"type": "integer", "format": "int64"}
	default:
		return map[string]string{"type": "string"}
	}
}

func response(description string, schema string) map[string]any {
	return map[string]any{
		"description": description,
		"content": map[string]any{
			"application/json": map[string]any{"schema": schemaRef(schema)},
		},
	}
}

func schemas(structs map[string]thriftStruct) map[string]any {
	names := make([]string, 0, len(structs))
	for name := range structs {
		names = append(names, name)
	}
	sort.Strings(names)
	out := map[string]any{}
	for _, name := range names {
		st := structs[name]
		properties := map[string]any{}
		var required []string
		for _, field := range st.Fields {
			properties[field.Name] = typeSchema(field.Type)
			if field.Required {
				required = append(required, field.Name)
			}
		}
		schema := map[string]any{"type": "object", "properties": properties}
		if len(required) > 0 {
			schema["required"] = required
		}
		out[name] = schema
	}
	out["OpenAPI"] = map[string]string{"type": "object"}
	return out
}

func typeSchema(typ string) map[string]any {
	typ = strings.TrimSpace(typ)
	if strings.HasPrefix(typ, "list<") && strings.HasSuffix(typ, ">") {
		inner := strings.TrimSuffix(strings.TrimPrefix(typ, "list<"), ">")
		return map[string]any{"type": "array", "items": typeSchema(inner)}
	}
	switch typ {
	case "string":
		return map[string]any{"type": "string"}
	case "bool":
		return map[string]any{"type": "boolean"}
	case "i32":
		return map[string]any{"type": "integer", "format": "int32"}
	case "i64":
		return map[string]any{"type": "integer", "format": "int64"}
	case "Timestamp":
		return map[string]any{"type": "string", "format": "date-time"}
	case "JSON":
		return map[string]any{"type": "object"}
	default:
		return schemaRef(typ)
	}
}

func httpRoute(annotations map[string]string) (string, string) {
	if method := annotations["http.method"]; method != "" {
		return strings.ToUpper(method), hertzPath(annotations["http.path"])
	}
	for _, item := range []struct {
		key    string
		method string
	}{
		{"api.get", "GET"},
		{"api.post", "POST"},
		{"api.put", "PUT"},
		{"api.patch", "PATCH"},
		{"api.delete", "DELETE"},
		{"api.options", "OPTIONS"},
		{"api.head", "HEAD"},
	} {
		if path := annotations[item.key]; path != "" {
			return item.method, hertzPath(path)
		}
	}
	return "", ""
}

func hertzPath(path string) string {
	re := regexp.MustCompile(`\{([A-Za-z_][A-Za-z0-9_]*)\}`)
	return re.ReplaceAllString(path, `:$1`)
}

func openAPIPath(path string) string {
	re := regexp.MustCompile(`:([A-Za-z_][A-Za-z0-9_]*)`)
	return re.ReplaceAllString(path, `{$1}`)
}

func schemaRef(name string) map[string]any {
	return map[string]any{"$ref": "#/components/schemas/" + name}
}

func stripComment(line string) string {
	if i := strings.Index(line, "//"); i >= 0 {
		return line[:i]
	}
	return line
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
